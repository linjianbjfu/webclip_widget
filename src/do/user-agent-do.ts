/**
 * One Durable Object per user. Holds every session that user owns: the event
 * log, the turn table and one workspace per session.
 *
 * The object is addressed by `idFromName(userId)`, so all of a user's requests
 * land on the same instance and can share in-memory state (the subscriber hub,
 * the live pi sessions). Nothing in memory may be treated as durable — the
 * instance is evicted routinely and rebuilt from SQLite.
 */

import { DurableObject } from "cloudflare:workers";

import { initializeSchema } from "../fs/schema.ts";
import { WorkspaceFs } from "../fs/workspace-fs.ts";

/** Bindings declared in wrangler.jsonc; the concrete shape is generated by `wrangler types`. */
export type Env = Cloudflare.Env;

export class UserAgentDO extends DurableObject<Env> {
  readonly #sql: SqlStorage;
  /** One filesystem façade per session, rebuilt lazily after an eviction. */
  readonly #workspaces = new Map<string, WorkspaceFs>();

  constructor(ctx: DurableObjectState, env: Env) {
    super(ctx, env);
    this.#sql = ctx.storage.sql;
    initializeSchema(this.#sql);
  }

  /** Test seam: the schema is private, but tests need the same handle. */
  get sqlForTest(): SqlStorage {
    return this.#sql;
  }

  workspace(sessionId: string): WorkspaceFs {
    let fs = this.#workspaces.get(sessionId);
    if (!fs) {
      fs = new WorkspaceFs(this.#sql, sessionId);
      this.#workspaces.set(sessionId, fs);
    }
    return fs;
  }

  async fetch(_request: Request): Promise<Response> {
    return new Response("not implemented", { status: 501 });
  }
}
